import { supabase } from "./api";
import { SUPPORT_SESSION_KEY } from "../components/SupportSessionBanner";

/**
 * Double authentification (TOTP, Supabase Auth MFA) — KLT-0120.
 *
 * Un compte qui a enrôlé un facteur se connecte d'abord au niveau aal1 (mot de
 * passe, Google, lien magique) ; il doit saisir un code pour passer en aal2.
 */

/** true si la session doit encore être vérifiée par un code. */
export async function needsMfaChallenge(): Promise<boolean> {
  try {
    const { data, error } = await supabase.auth.mfa.getAuthenticatorAssuranceLevel();
    if (error || !data) return false;
    return data.nextLevel === "aal2" && data.currentLevel !== "aal2";
  } catch {
    return false;
  }
}

/** Session support ouverte depuis le panel admin : le code du client n'est pas demandé. */
export function isSupportSession(): boolean {
  try { return !!sessionStorage.getItem(SUPPORT_SESSION_KEY); } catch { return false; }
}

export function mfaUrl(redirect: string): string {
  return `/auth/mfa?redirect=${encodeURIComponent(redirect)}`;
}

